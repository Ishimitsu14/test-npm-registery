import { State } from '@ddd/core';
import { Entity, EntityConstructor } from '@ddd/domain';

import { DbEntityEntrySnapshot, DbEntityStatus, IDbEntityEntry } from './IDbEntityEntry';

export class DbEntityEntry<TEntity extends Entity> implements IDbEntityEntry<TEntity> {
  private _entryIdentificator = Symbol('ENTRY_IDENTIFICATOR');

  private _entity: TEntity;
  private _status: DbEntityStatus;
  private _statusTimestamp: Date;

  constructor(entity: TEntity, status: DbEntityStatus) {
    this._entity = entity;
    this._status = status;

    this._statusTimestamp = new Date();
  }

  get entityType(): EntityConstructor<TEntity> {
    return Entity.getTypeOfInstance(this._entity);
  }

  get status(): DbEntityStatus {
    return this._status;
  }

  get entity(): TEntity {
    return this._entity;
  }

  get statusTimestamp(): Date {
    return this._statusTimestamp;
  }

  hasPrimaryKey(): boolean {
    return this._entity.hasPrimaryKey();
  }

  updateStatus(status: DbEntityStatus): void {
    this._status = status;
    this._statusTimestamp = new Date();
  }

  getState(): State<TEntity> {
    return State.getStateFromReference(this._entity);
  }

  updateState(entity: TEntity | State<TEntity>): void {
    const state = State.isExtends(entity) ? entity : State.getStateFromReference(entity);
    State.applyState(this._entity, state);
  }

  getCurrentSnapshot(): DbEntityEntrySnapshot<TEntity> {
    return {
      entry: this._entryIdentificator,
      state: this.getState(),
      status: this.status,
      statusTimestamp: this.statusTimestamp,
    };
  }

  revertBySnapshot(snapshot: DbEntityEntrySnapshot<TEntity>): void {
    if (snapshot?.entry !== this._entryIdentificator) throw new TypeError(`${DbEntityEntry.name} revertBySnapshot: snapshot not generated by this entry.`);

    this._status = snapshot.status;
    this._statusTimestamp = snapshot.statusTimestamp;
    this.updateState(snapshot.state);
  }
}
